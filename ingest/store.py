def write_database(db_path, tables: list, frames: dict, canonical: dict, report: list, assumptions: dict) -> None:
    """Write the whole dataset, replacing any file already at db_path.

    The data is written to "<name>.tmp" first and moved into place at the end, so a
    failure half way never leaves a broken database where a good one was.
    """
    target = Path(db_path)
    temporary = target.with_name(target.name + ".tmp")
    if temporary.exists():
        temporary.unlink()
    conn = sqlite3.connect(str(temporary))
    try:
        # The temporary file is thrown away on any failure, so the usual crash protection
        # of SQLite is not needed while filling it. This makes large loads much faster.
        conn.execute("PRAGMA journal_mode = OFF")
        conn.execute("PRAGMA synchronous = OFF")
        conn.executescript(SCHEMA)
        for table in tables:
            with conn:                                   # one transaction per table
                _write_generic_table(conn, table, frames[table["name"]])
        for name in ("suppliers", "products", "sales", "inventory"):
            with conn:
                _insert_frame(conn, name, canonical[name], CANONICAL_DTYPES[name])
        with conn:
            conn.executescript(INDEXES)
            conn.executemany("INSERT INTO _cleaning_report VALUES (?, ?, ?, ?)",
                             [(row["step"], row["table"], int(row["count"]), row["detail"]) for row in report])
            conn.executemany("INSERT INTO _assumptions VALUES (?, ?)",
                             [(name, str(value)) for name, value in assumptions.items()])
            _write_capabilities(conn)
    except BaseException:
        conn.close()
        temporary.unlink(missing_ok=True)
        raise
    conn.close()
    os.replace(temporary, target)


def _write_generic_table(conn: sqlite3.Connection, table: dict, frame: pd.DataFrame) -> None:
    columns = table["columns"]
    definitions = ", ".join(f"{_quote(column['name'])} {_SQL_TYPE[column['dtype']]}" for column in columns)
    conn.execute(f"CREATE TABLE {_quote(table['name'])} ({definitions})")
    ordered = frame[[column["name"] for column in columns]]
    _insert_frame(conn, table["name"], ordered, [column["dtype"] for column in columns])
    conn.execute("INSERT INTO _tables VALUES (?, ?, ?, ?, ?)",
                 (table["name"], table["source_file"], table["source_sheet"], len(frame), table["kind"]))
    for column in columns:
        nulls, distinct, low, high = _column_facts(frame[column["name"]], column["dtype"])
        conn.execute("INSERT INTO _columns VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                     (table["name"], column["name"], column["original_header"], column["dtype"],
                      nulls, distinct, low, high, column.get("role")))


