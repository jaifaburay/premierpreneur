# Capabilities
# --------------------------------------------------------------------------------------
def _exists(conn: sqlite3.Connection, sql: str) -> bool:
    return conn.execute(sql).fetchone() is not None


def _column_found_for(conn: sqlite3.Connection, roles: tuple, include_used: bool = True) -> str:
    """One sentence about a column that was found for one of these roles but gave no usable
    data; "" when no such column was found at all.

    Two places are checked: _columns (a column holds the role, yet nothing usable came out
    of it) and the cleaning report (a column was named like the role but was empty or of
    the wrong type; api.py writes those rows under the step "unusable_<role>").
    Only names made by this package appear in the sentence, never text from the file.
    """
    if include_used and _has_table(conn, "_columns"):
        for role in roles:
            found = conn.execute("SELECT column_name, table_name FROM _columns WHERE role = ? LIMIT 1", (role,)).fetchone()
            if found:
                return (f"Column {found[0]} in {found[1]} was read as {role_words(role)}, "
                        "but no usable value came out of it.")
    if _has_table(conn, "_cleaning_report"):
        for role in roles:
            found = conn.execute("SELECT detail FROM _cleaning_report WHERE step = ? LIMIT 1",
                                 (f"unusable_{role}",)).fetchone()
            if found:
                return found[0]
    return ""


def compute_capabilities(conn: sqlite3.Connection) -> dict:
    """Work out what this dataset can support: {name: (available, reason)}.

    Each capability needs certain data (spec section 3.4). When the data is not there, the
    reason says why, truthfully: "add a column" only when no column for it was found; when
    a column was found but was empty or unusable, the reason names that column instead.
    """
    has_sales = _exists(conn, "SELECT 1 FROM sales LIMIT 1")
    has_price = _exists(conn, "SELECT 1 FROM sales WHERE unit_price_at_sale IS NOT NULL LIMIT 1")
    has_cost = _exists(conn, "SELECT 1 FROM products WHERE unit_cost IS NOT NULL LIMIT 1")
    has_stock = _exists(conn, "SELECT 1 FROM inventory LIMIT 1")
    has_products = _exists(conn, "SELECT 1 FROM products LIMIT 1")
    has_lead_time = _exists(conn, "SELECT 1 FROM products p JOIN suppliers s ON s.supplier_id = p.supplier_id "
                                  "WHERE s.lead_time_days IS NOT NULL LIMIT 1")
    has_default_lead = _exists(conn, "SELECT 1 FROM _assumptions WHERE name = 'default_lead_time_days'")

    def reason_for(roles: tuple, when_no_column: str, when_column_unusable: str, include_used: bool = True) -> str:
        found = _column_found_for(conn, roles, include_used)
        return f"{found} {when_column_unusable}" if found else when_no_column

    no_stock = reason_for(
        ("on_hand",),
        "This dataset has no stock levels. Add a column with units on hand for each product.",
        "So there are no stock levels; fill in the units on hand for each product.")
    no_cost = reason_for(
        ("unit_cost",),
        "No product has a unit cost. Add a column with what each product costs you to buy.",
        "So no product has a unit cost; fill in what each product costs you to buy.")
    no_price = reason_for(
        ("unit_price", "revenue"),
        "The sales rows have no price. Add a unit price or a revenue column to the sales data.",
        "So the sales rows have no price; fill in the unit price or the revenue.")
    no_products = "This dataset has no products. Add a sheet with a product column."

    # Lead time: it may exist on a supplier sheet that no product points at.
    if _exists(conn, "SELECT 1 FROM suppliers WHERE lead_time_days IS NOT NULL LIMIT 1"):
        no_lead = ("Supplier lead times were found, but no product is linked to a supplier that has one. "
                   "Add the supplier to each product, or set a default lead time in days.")
    else:
        no_lead = reason_for(
            ("lead_time_days",),
            "No supplier lead time is known for any product. Add a lead time column, or set a "
            "default lead time in days.",
            "So no supplier lead time is known; fill it in, or set a default lead time in days.")

    # Sales: a sales sheet may have been recognised and still have no usable row.
    sales_sheet = None
    if _has_table(conn, "_tables"):
        sales_sheet = conn.execute("SELECT table_name FROM _tables WHERE kind = 'transactions' LIMIT 1").fetchone()
    if sales_sheet:
        no_sales = (f"A sales sheet was found ({sales_sheet[0]}), but none of its rows has a product, a date "
                    "and a quantity above zero, so there are no sales rows. Check those three columns.")
    else:
        no_sales = reason_for(
            ("sale_date", "quantity"),
            "This dataset has no sales rows. Add a sheet with one row per sale that has a "
            "product, a date and a quantity.",
            "So no sales rows could be read; a sales sheet needs a product, a date and a quantity.",
            include_used=False)

    def first_problem(*checks) -> str:
        """The reason of the first requirement that is not met, or "" when all are met."""
        for ok, reason in checks:
            if not ok:
                return reason
        return ""

    reasons = {
        "sales_analysis": first_problem((has_sales, no_sales)),
        "revenue": first_problem((has_sales, no_sales), (has_price, no_price)),
        "margin": first_problem((has_sales, no_sales), (has_price, no_price), (has_cost, no_cost)),
        "inventory_status": first_problem((has_sales, no_sales), (has_stock, no_stock)),
        "supplier_terms": first_problem((has_products, no_products), (has_lead_time or has_default_lead, no_lead)),
        # a restock plan also needs a lead time: the planner cannot say when stock would arrive without one
        "restock_planning": first_problem((has_sales, no_sales), (has_stock, no_stock), (has_cost, no_cost),
                                          (has_lead_time or has_default_lead, no_lead)),
        "discount_evaluation": first_problem((has_sales, no_sales), (has_price, no_price), (has_cost, no_cost)),
    }
    return {name: (reasons[name] == "", reasons[name]) for name in CAPABILITY_NAMES}


def _write_capabilities(conn: sqlite3.Connection) -> None:
    conn.execute("DELETE FROM _capabilities")
    conn.executemany("INSERT INTO _capabilities VALUES (?, ?, ?)",
                     [(name, 1 if available else 0, reason)
                      for name, (available, reason) in compute_capabilities(conn).items()])


