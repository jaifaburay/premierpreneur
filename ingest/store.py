# Assumptions
# --------------------------------------------------------------------------------------
def validate_assumptions(values: dict) -> dict:
    """Check owner-supplied defaults. Returns {name: whole number, or None to remove it}.
    Raises ValueError with a plain message for an unknown name or a value out of range."""
    checked = {}
    for name, value in (values or {}).items():
        if name not in ASSUMPTION_RANGES:
            known = ", ".join(sorted(ASSUMPTION_RANGES))
            raise ValueError(f"'{name}' is not a setting that can be assumed. The settings are: {known}.")
        if value is None:
            checked[name] = None
            continue
        low, high = ASSUMPTION_RANGES[name]
        problem = f"{name} must be a whole number between {low} and {high}, got {value!r}."
        if isinstance(value, bool):
            raise ValueError(problem)
        try:
            number = float(value)
        except (TypeError, ValueError):
            raise ValueError(problem)
        if number != int(number) or not low <= number <= high:
            raise ValueError(problem)
        checked[name] = int(number)
    return checked


def set_assumptions(db_path, **values) -> dict:
    """Store owner-supplied defaults in an existing dataset and switch capabilities on or off
    to match. A value of None removes that default; names not mentioned keep their value.

        set_assumptions("store.db", default_lead_time_days=14, default_moq=1)

    Returns summarize(db_path). Raises ValueError for an unknown name or a bad value.
    """
    checked = validate_assumptions(values)
    if not Path(db_path).is_file():
        raise ValueError("There is no dataset at that location; load a file first.")
    conn = sqlite3.connect(str(db_path))
    try:
        with conn:
            conn.execute("CREATE TABLE IF NOT EXISTS _assumptions (name TEXT PRIMARY KEY, value TEXT)")
            conn.execute("CREATE TABLE IF NOT EXISTS _capabilities (name TEXT PRIMARY KEY, available INTEGER, reason TEXT)")
            current = dict(conn.execute("SELECT name, value FROM _assumptions").fetchall())
            for name, number in checked.items():
                if number is None:
                    current.pop(name, None)
                else:
                    current[name] = str(number)
            conn.execute("DELETE FROM _assumptions")
            conn.executemany("INSERT INTO _assumptions VALUES (?, ?)", sorted(current.items()))
            _write_capabilities(conn)
    finally:
        conn.close()
    return summarize(db_path)


# --------------------------------------------------------------------------------------
# Reading back
# --------------------------------------------------------------------------------------
def _has_table(conn: sqlite3.Connection, name: str) -> bool:
    return conn.execute("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?", (name,)).fetchone() is not None


def summarize(db_path) -> dict:
    """A small description of a dataset file: its tables and columns, what it can support,
    how many rows the four standard tables hold, the first and last sale date, and the
    owner's defaults. Works on older databases too (missing parts come back empty)."""
    if not Path(db_path).is_file():
        raise ValueError("There is no dataset at that location; load a file first.")
    conn = sqlite3.connect(str(db_path))
    try:
        tables = []
        if _has_table(conn, "_tables") and _has_table(conn, "_columns"):
            for name, rows, kind in conn.execute("SELECT table_name, row_count, kind FROM _tables ORDER BY rowid"):
                columns = [{"name": column, "dtype": dtype, "role": role}
                           for column, dtype, role in conn.execute(
                               "SELECT column_name, dtype, role FROM _columns WHERE table_name = ? ORDER BY rowid", (name,))]
                tables.append({"name": name, "rows": rows, "kind": kind, "columns": columns})

        capabilities = {}
        if _has_table(conn, "_capabilities"):
            for name, available, reason in conn.execute("SELECT name, available, reason FROM _capabilities"):
                capabilities[name] = {"available": bool(available), "reason": reason or ""}

        counts = {}
        for name in ("products", "sales", "inventory", "suppliers"):
            counts[name] = conn.execute(f"SELECT COUNT(*) FROM {_quote(name)}").fetchone()[0] \
                if _has_table(conn, name) else 0

        first, last = (None, None)
        if _has_table(conn, "sales"):
            first, last = conn.execute("SELECT MIN(sale_date), MAX(sale_date) FROM sales").fetchone()

        assumptions = {}
        if _has_table(conn, "_assumptions"):
            for name, value in conn.execute("SELECT name, value FROM _assumptions"):
                assumptions[name] = int(value) if str(value).lstrip("-").isdigit() else value
    finally:
        conn.close()
    return {"tables": tables, "capabilities": capabilities, "canonical_counts": counts,
            "date_range": {"first": first, "last": last}, "assumptions": assumptions}


def read_report(db_path) -> list:
    """The cleaning report stored in a dataset file, as a list of dictionaries."""
    conn = sqlite3.connect(str(db_path))
    try:
        if not _has_table(conn, "_cleaning_report"):
            return []
        return [{"step": step, "table": table, "count": count, "detail": detail}
                for step, table, count, detail in conn.execute(
                    "SELECT step, table_name, count, detail FROM _cleaning_report ORDER BY rowid")]
    finally:
        conn.close()
