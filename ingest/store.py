"""
Writing a cleaned dataset to one SQLite file, and reading its summary back.

The file layout is the data contract in docs/M3_BUILD_SPEC.md, section 3:

  generic layer    one table per cleaned sheet (t_...), plus _tables and _columns that
                   describe them, and _cleaning_report with one row per cleaning action
  canonical layer  products, sales, inventory, suppliers: the four tables the tools read
  _capabilities    which analyses this dataset supports, with a reason when it does not
  _assumptions     defaults the owner supplied (default lead time, default minimum order)

SQL safety: table and column names are generated by this package from a fixed alphabet and
are checked again before use; every value from the file is passed as a bound parameter.
Cell text is never pasted into an SQL statement.
"""
from __future__ import annotations

import os
import re
import sqlite3
from pathlib import Path

import pandas as pd

from .roles import role_words

BATCH_ROWS = 50_000
_SAFE_NAME = re.compile(r"[a-z][a-z0-9_]{0,39}\Z")
_SQL_TYPE = {"text": "TEXT", "date": "TEXT", "integer": "INTEGER", "bool": "INTEGER", "number": "REAL"}

SCHEMA = """
CREATE TABLE _tables (table_name TEXT PRIMARY KEY, source_file TEXT, source_sheet TEXT,
                      row_count INTEGER, kind TEXT);
CREATE TABLE _columns (table_name TEXT, column_name TEXT, original_header TEXT, dtype TEXT,
                       null_count INTEGER, distinct_count INTEGER, min_value TEXT, max_value TEXT,
                       role TEXT, PRIMARY KEY (table_name, column_name));
CREATE TABLE _cleaning_report (step TEXT, table_name TEXT, count INTEGER, detail TEXT);
CREATE TABLE _capabilities (name TEXT PRIMARY KEY, available INTEGER, reason TEXT);
CREATE TABLE _assumptions (name TEXT PRIMARY KEY, value TEXT);

CREATE TABLE suppliers (supplier_id TEXT PRIMARY KEY, supplier_name TEXT, lead_time_days INTEGER,
                        payment_terms TEXT);
CREATE TABLE products (product_id TEXT PRIMARY KEY, product_name TEXT NOT NULL, category TEXT,
                       unit_price REAL, unit_cost REAL, supplier_id TEXT, moq INTEGER NOT NULL DEFAULT 1);
CREATE TABLE sales (sale_id TEXT PRIMARY KEY, sale_date TEXT NOT NULL, product_id TEXT NOT NULL,
                    quantity INTEGER NOT NULL, unit_price_at_sale REAL,
                    discount_pct REAL NOT NULL DEFAULT 0, channel TEXT);
CREATE TABLE inventory (product_id TEXT PRIMARY KEY, on_hand INTEGER NOT NULL,
                        reorder_point INTEGER NOT NULL DEFAULT 0, last_counted TEXT);
"""
INDEXES = """
CREATE INDEX idx_sales_date ON sales(sale_date);
CREATE INDEX idx_sales_product ON sales(product_id);
"""

# Column types of the four standard tables, in column order.
CANONICAL_DTYPES = {
    "suppliers": ["text", "text", "integer", "text"],
    "products": ["text", "text", "text", "number", "number", "text", "integer"],
    "sales": ["text", "date", "text", "integer", "number", "number", "text"],
    "inventory": ["text", "integer", "integer", "date"],
}

# The owner-supplied defaults that are understood, with their allowed range.
ASSUMPTION_RANGES = {
    "default_lead_time_days": (0, 365),
    "default_moq": (1, 1_000_000),
}

CAPABILITY_NAMES = ("sales_analysis", "revenue", "margin", "inventory_status", "supplier_terms",
                    "restock_planning", "discount_evaluation")


def _quote(name: str) -> str:
    """A table or column name in double quotes. Only names made by this package get here;
    the check is a second lock on the same door."""
    if not _SAFE_NAME.match(name):
        raise ValueError(f"unsafe table or column name: {name!r}")
    return f'"{name}"'


def _python_values(series: pd.Series, dtype: str) -> list:
    """One column as plain Python values that sqlite3 accepts: str, int, float or None."""
    values = series.to_numpy(dtype=object, na_value=None).tolist()
    if dtype in ("integer", "bool"):
        return [None if value is None else int(value) for value in values]
    if dtype == "number":
        return [None if value is None else float(value) for value in values]
    return [None if value is None else str(value) for value in values]


def _insert_frame(conn: sqlite3.Connection, table_name: str, frame: pd.DataFrame, dtypes: list) -> None:
    """Insert every row of a DataFrame, 50,000 rows at a time."""
    placeholders = ", ".join("?" for _ in dtypes)
    statement = f"INSERT INTO {_quote(table_name)} VALUES ({placeholders})"
    for start in range(0, len(frame), BATCH_ROWS):
        piece = frame.iloc[start:start + BATCH_ROWS]
        columns = [_python_values(piece[name], dtype) for name, dtype in zip(frame.columns, dtypes)]
        conn.executemany(statement, zip(*columns))


def _as_text(value, dtype: str):
    """A minimum or maximum as short text for the data dictionary."""
    if value is None or pd.isna(value):
        return None
    if dtype in ("integer", "bool"):
        return str(int(value))
    if dtype == "number":
        return str(round(float(value), 6))
    return str(value)[:60]


def _column_facts(series: pd.Series, dtype: str) -> tuple:
    """(null_count, distinct_count, min_value, max_value) for the data dictionary."""
    present = series.dropna()
    low = present.min() if len(present) else None
    high = present.max() if len(present) else None
    return (int(series.isna().sum()), int(present.nunique()), _as_text(low, dtype), _as_text(high, dtype))


